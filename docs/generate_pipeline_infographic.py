t = np.linspace(0, 90, 4000)
signal = np.zeros_like(t)
speech_regions = [(5, 12), (18, 25), (30, 38), (45, 52), (58, 62), (70, 78), (82, 88)]

for start, end in speech_regions:
    mask = (t >= start) & (t <= end)
    duration = end - start
    env = np.exp(-3 * ((t[mask] - (start + end) / 2) / (duration / 2)) ** 2)
    amp = 0.4 + 0.4 * rng.random()
    sig = np.zeros(mask.sum())
    for freq in rng.uniform(2, 15, 5):
        sig += rng.uniform(0.1, 0.4) * np.sin(2 * np.pi * freq * t[mask] + rng.uniform(0, 6.28))
    signal[mask] = amp * sig / np.abs(sig).max() * env

signal += rng.normal(0, 0.015, len(t))

x_coords = np.linspace(0.02, 0.98, len(t))
upper = 0.40 + signal * 0.22
lower = 0.40 - signal * 0.22

for start, end in speech_regions:
    x0 = 0.02 + (start / 90) * 0.96
    w = ((end - start) / 90) * 0.96
    ax5.axvspan(x0, x0 + w, ymin=0.2, ymax=0.85, facecolor=ACCENT, alpha=0.06)

