def load_frame(prefix):
    """Load a frame PNG, corrected for pixel aspect ratio."""
    path = os.path.join(FRAMES_DIR, prefix)
    img = Image.open(path)
    # Resize to correct display aspect ratio
    img = img.resize((display_w, display_h), Image.LANCZOS)
    return np.array(img)


def get_detections(timestamp_key):
    """Get detection list for a timestamp."""
    return det_meta["detections"].get(timestamp_key, [])


