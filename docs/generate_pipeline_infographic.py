    face_in_crop_y1 = my1 - cy1
    face_in_crop_x2 = mx2 - cx1
    face_in_crop_y2 = my2 - cy1
    face_in_crop_x1 = max(0, face_in_crop_x1)
    face_in_crop_y1 = max(0, face_in_crop_y1)
    face_in_crop_x2 = min(cropped.shape[1], face_in_crop_x2)
    face_in_crop_y2 = min(cropped.shape[0], face_in_crop_y2)
    mask_img[face_in_crop_y1:face_in_crop_y2, face_in_crop_x1:face_in_crop_x2] = 0

